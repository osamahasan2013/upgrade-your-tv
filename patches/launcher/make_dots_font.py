CELL = 140; R = 52; ADV = 6 * CELL
UPM = 1000

def circle(pen, cx, cy, r):
    n = 8
    pts = []
    k = r / math.cos(math.pi / n)
    # clockwise: angles decreasing
    on = [(cx + r * math.cos(-2 * math.pi * i / n), cy + r * math.sin(-2 * math.pi * i / n)) for i in range(n)]
    off = [(cx + k * math.cos(-2 * math.pi * (i + 0.5) / n), cy + k * math.sin(-2 * math.pi * (i + 0.5) / n)) for i in range(n)]
    pen.moveTo((round(on[0][0]), round(on[0][1])))
    for i in range(n):
        nxt = on[(i + 1) % n]
        pen.qCurveTo((round(off[i][0]), round(off[i][1])), (round(nxt[0]), round(nxt[1])))
    pen.closePath()

def glyph(rows):
    pen = TTGlyphPen(None)
    for r, line in enumerate(rows):
        for c, ch in enumerate(line):
            if ch == '1':
                cx = CELL // 2 + c * CELL + CELL // 4
                cy = (6 - r) * CELL + CELL // 2
                circle(pen, cx, cy, R)
    return pen.glyph()

